// PQ-75. The projection is arithmetic, and arithmetic nobody can check is a
// number nobody trusts twice. The sizes it uses are FIPS 204 parameter sets —
// not a rule of thumb from a blog post — and the page that states them is
// generated from the same table the code computes with, so the two cannot
// drift. That is the whole reason this is a generator and not a hand-written
// page: `docs/background.md` already carried "roughly 4 KB per certificate",
// and roughly is exactly what a planner cannot use.
//
// It also draws the boundary this milestone keeps having to restate: the server
// flight is the half of the handshake PQ-72 and PQ-74 are about, and
// `--size-sweep` is the other half. They fail for the same reason in opposite
// directions, and conflating them is how somebody shortens a certificate chain
// to fix a ClientHello problem.

var updateCerts = flag.Bool("update-certs", false, "rewrite docs/certificates.md")

func TestTheCertificatePageMatchesTheTable(t *testing.T) {
	page := certificatePage()
	path := filepath.Join("..", "..", "docs", "certificates.md")
	if *updateCerts {
		if err := os.WriteFile(path, []byte(page), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v — run `go test ./internal/verdict/ -update-certs`", err)
	}
	if page != string(want) {
		t.Errorf("docs/certificates.md no longer matches the parameter table the code computes with.\n"+
			"If a size changed on purpose, re-run with -update-certs and read the diff as what it is:\n"+
			"every projection this tool has ever reported was computed with the old number.\n\ngot:\n%s", page)
	}
}

// The page states a worked example, and the example has to be the code's own
// answer rather than a number typed next to it — the failure this whole
// milestone is about, one level up.
func TestThePageExampleIsTheCodesOwnArithmetic(t *testing.T) {
	chain := exampleChain()
	f, ok := chainProjection("example:443", &probe.Result{Chain: chain, ChainBytes: 4000}, 14000)
	if !ok {
		t.Fatal("the example chain produced no projection")
	}
	page := certificatePage()
	// The total the page prints has to be the one the finding carries.
	if f.Value == nil {
		t.Fatal("the projection carries no value")
	}
	total := fmt.Sprintf("%d", int(*f.Value))
	if !strings.Contains(page, total) {
		t.Errorf("the page does not contain the projection's own total (%s)", total)
	}
}

// Every parameter set in the code is in the page: a set added and not described
// is a size somebody will find in a message with nowhere to look it up.
func TestEveryParameterSetIsOnThePage(t *testing.T) {
	page := certificatePage()
	for _, p := range mldsaSets {
		if !strings.Contains(page, p.Name) {
			t.Errorf("%s is in the table and not on the page", p.Name)
		}
		for _, n := range []int{p.Key, p.Sig} {
			if !strings.Contains(page, fmt.Sprintf("%d", n)) {
				t.Errorf("%s: %d is not on the page", p.Name, n)
			}
		}
	}
}

// The generator behind docs/certificates.md (PQ-75).
//
// In a test file, like the schema and compatibility generators, so none of it
// is linked into the binary — a file in this package has the same access to
// `chainProjection` as the implementation does, which is what lets the page's
// worked example be the code's own answer rather than a number typed next to a
// formula. That is the failure this whole milestone is about, one level up.

// exampleChain is the chain the page works through: a leaf and one
// intermediate, ECDSA P-256, with the key and signature sizes those have in
// DER. Deliberately the common case rather than an interesting one — the page
// exists to let somebody check the method, not to show off an edge.
func exampleChain() []probe.Cert {
	return []probe.Cert{
		{Subject: "leaf", Bytes: 1400, KeyBytes: 91, SigBytes: 71,
			KeyAlg: "ECDSA", KeyBits: 256, SigAlg: "ECDSA-SHA256"},
		{Subject: "intermediate", IsCA: true, Bytes: 1500, KeyBytes: 91, SigBytes: 71,
			KeyAlg: "ECDSA", KeyBits: 256, SigAlg: "ECDSA-SHA256"},
	}
}

func certificatePage() string {
	var b strings.Builder

	b.WriteString(`<!-- GENERATED by go test ./internal/verdict/ -update-certs — do not edit by hand. -->

# Certificates: the next migration, and its arithmetic

Post-quantum **key exchange** is the migration happening now, and it is what
pqprobe was built for. Post-quantum **authentication** is the next one, and it
fails in the same shape for the same reason: the thing that has to travel gets
too big for the path it travels on.

The difference is that this one can be measured before it starts. The chain
arrived in the handshake, so what it costs today is known — and what it would
cost signed post-quantum is arithmetic over two numbers per certificate. This
page is that arithmetic, generated from the same table the code computes with,
so the page and the constant cannot drift.

## The sizes

FIPS 204, the ML-DSA standard. Not a rule of thumb: these are the parameter sets
a certificate authority chooses between.

`)

	fmt.Fprintln(&b, "| Parameter set | Public key | Signature | Both |")
	fmt.Fprintln(&b, "|---|---|---|---|")
	for _, p := range mldsaSets {
		fmt.Fprintf(&b, "| `%s` | %d B | %d B | %d B |\n", p.Name, p.Key, p.Sig, p.Key+p.Sig)
	}
	fmt.Fprintf(&b, "\nFor comparison, what comes *out*: an ECDSA P-256 public key is 91 bytes of\n"+
		"subjectPublicKeyInfo and its signature 71 bytes in DER — %d together, against\n"+
		"%d for ML-DSA-65. RSA-2048 is larger at 270 and 256, which is why an RSA chain\n"+
		"grows less in relative terms and still ends up in the same place.\n",
		91+71, mldsaSet("ML-DSA-65").Key+mldsaSet("ML-DSA-65").Sig)

	b.WriteString(`
## What the projection does, exactly

A post-quantum certificate is the same certificate with two fields replaced: the
subjectPublicKeyInfo and the signature. So, per certificate:

    projected = bytes − key_bytes − sig_bytes + ML-DSA key + ML-DSA signature

`)

	chain := exampleChain()
	f, ok := chainProjection("example:443", &probe.Result{Chain: chain, ChainBytes: 2900}, 14000)
	if !ok {
		// Unreachable with the fixture above, and a panic here would be a
		// generator writing a page with a hole in it.
		panic("verdict: the example chain produced no projection")
	}

	fmt.Fprintf(&b, "Worked through, for a leaf and one intermediate:\n\n")
	fmt.Fprintln(&b, "| Certificate | Today | Key | Signature | Under ML-DSA-65 |")
	fmt.Fprintln(&b, "|---|---|---|---|---|")
	p := mldsaSet("ML-DSA-65")
	total := 0
	for i, c := range chain {
		proj := c.Bytes - c.KeyBytes - c.SigBytes + p.Key + p.Sig
		total += proj
		fmt.Fprintf(&b, "| %s | %d B | %d B | %d B | **%d B** |\n",
			certLabel(c, i), c.Bytes, c.KeyBytes, c.SigBytes, proj)
	}
	fmt.Fprintf(&b, "| | | | | **%d B total** |\n", total)

	fmt.Fprintf(&b, "\nWhich is what the finding says:\n\n    %s\n", f.Message)

	b.WriteString(`
### What it deliberately does not model

- **The AlgorithmIdentifier** around each field: tens of bytes against
  thousands.
- **A chain that gains or loses a certificate** in the migration. That is
  somebody's decision, not arithmetic.
- **A hybrid deployment** where some keys stay classical.
- **Anything about whether the migration happens at all.** Nothing serves ML-DSA
  certificates today. The projection says what *this* chain would weigh if all of
  it moved, which is the number to plan against — not a prediction that it will.

### Cross-signed chains

A cross-signed chain carries the same key twice, signed by two issuers, and both
copies move. If your chain is cross-signed for compatibility with an old trust
store, the projection counts both — correctly, because both still have to travel.
That is also the clearest case for the advice in the finding: the cheapest
kilobytes in a post-quantum chain are the certificates you stop sending.

## Why this is about the server's flight

`)

	fmt.Fprintf(&b, `pqprobe measures sizes in both directions, and they are different problems:

| | Direction | What is too big | The check |
|---|---|---|---|
| Key exchange | client → server | the ClientHello, ~1.2 KB larger with ML-KEM | `+"`--size-sweep`"+`, `+"`hello_bytes`"+` |
| Authentication | server → client | the certificate flight, several KB larger with ML-DSA | `+"`chain-projection`"+`, `+"`--cert-headroom-warn`"+` |

They fail for the same reason in opposite directions, and the middleboxes that
object to one are not necessarily the ones that object to the other. Conflating
them is how somebody shortens a certificate chain to fix a ClientHello problem,
or raises an MTU to fix a chain that does not fit an initial congestion window.

The threshold on the server side is %d bytes by default: past roughly that, a
flight no longer fits the ten-segment initial congestion window most stacks
still ship, so the handshake costs a second round trip — or stops working, on a
path that already dislikes large flights. It is a default and not a law;
`+"`--cert-headroom-warn`"+` moves it and `+"`0`"+` turns it off.

## What to do with the number today

Nothing serves ML-DSA certificates yet, so the signature is not yours to choose.
What is yours is the **length of the chain**: one intermediate fewer is the
cheapest kilobytes there are, and it pays off twice — once now, in a smaller
flight, and again at four to five times the saving after the migration.

The inventory to plan against is the `+"`signatures`"+` finding: what every
certificate's key is, how big, and what signed it. See
[Findings](findings.md) for both, and [Background](background.md) for why a
handshake fails by hanging rather than by erroring when something on the path
objects to a size.
`, DefaultOptions().CertHeadroomWarn)

	return b.String()
}
